"""The area catalogue bundled with the integration: the shipped file, its routes, and the repository's fallback.

The file is generated by `tools/sync_areas.py` from the relay's own table; these tests pin what the providers
will rely on (Nord Pool codes, ENTSO-E sequence policies, the CET calendar) and that the repository answers the
bundled list only while the relay's is not held.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest
from homeassistant.core import HomeAssistant

from custom_components.spotnav.pricing.area_catalogue import (
    async_load_bundled,
    BUNDLED_PATH,
    parse_bundled,
)
from custom_components.spotnav.pricing.price_repository import PriceRepository
from custom_components.spotnav.pricing.relay_contract import RelayParseError
from tools.sync_areas import lost_routes, render

from .relay import BASE_URL, Clock, StubTransport

#: The areas Nord Pool's day-ahead market prices, by SpotNav id, with Nord Pool's own code.
NORD_POOL = {
    **{area: area for area in ("SE1", "SE2", "SE3", "SE4", "NO1", "NO2", "NO3", "NO4", "NO5", "DK1", "DK2")},
    **{area: area for area in ("FI", "EE", "LV", "LT", "AT", "BE", "FR", "NL", "PL", "BG")},
    "DE-LU": "GER",
    "RO": "TEL",
}

#: Areas on Eastern European time: their CET delivery day is not their own calendar day.
EET = ("FI", "EE", "LV", "LT", "BG", "RO", "GR")


def shipped() -> dict:
    return json.loads(BUNDLED_PATH.read_text(encoding="utf-8"))


@pytest.fixture
def bundled():
    return parse_bundled(shipped())


# ------------------------------------------------------------------ the shipped file


def test_the_shipped_file_is_read_whole(bundled) -> None:
    document = shipped()
    assert bundled.catalogue.version == 2
    assert len(bundled.catalogue.areas) == len(document["areas"]) == 39
    assert set(bundled.routes) == set(bundled.catalogue.area_ids)
    assert list(bundled.catalogue.area_ids) == sorted(bundled.catalogue.area_ids)


def test_the_shipped_file_is_as_the_sync_tool_writes_it() -> None:
    assert BUNDLED_PATH.read_text(encoding="utf-8") == render(shipped())


def test_no_area_without_a_provider(bundled) -> None:
    ids = set(bundled.catalogue.area_ids)
    assert not any(area.startswith("GB-") for area in ids)
    assert "ES-PVPC" not in ids
    for area_id, routes in bundled.routes.items():
        assert routes.entsoe is not None and routes.entsoe.eic == bundled.catalogue.area(area_id).eic


def test_nord_pool_codes(bundled) -> None:
    codes = {area_id: routes.nordpool for area_id, routes in bundled.routes.items() if routes.nordpool}
    assert codes == NORD_POOL
    assert bundled.routes["IT-NORTH"].nordpool is None and bundled.routes["CH"].nordpool is None


def test_entsoe_sequence_policies(bundled) -> None:
    for area_id in ("DE-LU", "AT"):
        route = bundled.routes[area_id].entsoe
        assert (route.sequence, route.expected_sequences, route.half_hourly) == ("1", ("1", "2"), False)
    route = bundled.routes["SE3"].entsoe
    assert (route.sequence, route.expected_sequences) == (None, ())
    assert bundled.routes["DE-LU"].entsoe.eic == "10Y1001A1001A82H"


def test_the_cet_calendar(bundled) -> None:
    for area_id in EET:
        assert bundled.routes[area_id].cet_market_tz == "Europe/Brussels", area_id
    assert bundled.routes["SE3"].cet_market_tz == "Europe/Stockholm"
    assert bundled.routes["DE-LU"].cet_market_tz == "Europe/Berlin"
    # Portugal keeps the relay's Madrid market day; the relay's own calendars are untouched.
    portugal = bundled.catalogue.area("PT")
    assert (portugal.tz, portugal.market_tz, bundled.routes["PT"].cet_market_tz) == (
        "Europe/Lisbon",
        "Europe/Madrid",
        "Europe/Madrid",
    )
    finland = bundled.catalogue.area("FI")
    assert finland.tz == finland.market_tz == "Europe/Helsinki"


def test_the_placeholder_source(bundled) -> None:
    assert {(area.source.name, area.source.url) for area in bundled.catalogue.areas} == {
        ("SpotNav", "https://spotnav.sensnology.se")
    }


# ------------------------------------------------------------------ refusals


@pytest.mark.parametrize(
    "damage",
    [
        lambda area: area.pop("routes"),
        lambda area: area["routes"].pop("cet_market_tz"),
        lambda area: area["routes"].__setitem__("cet_market_tz", "Mars/Olympus"),
        lambda area: area["routes"].__setitem__("nordpool", ""),
        lambda area: area["routes"]["entsoe"].pop("eic"),
        lambda area: area["routes"]["entsoe"].__setitem__("half_hourly", "no"),
        lambda area: area["routes"]["entsoe"].__setitem__("sequence", "3"),
        lambda area: area.__setitem__("tz", "Mars/Olympus"),
    ],
)
def test_any_fault_refuses_the_whole_file(damage) -> None:
    document = shipped()
    damage(next(area for area in document["areas"] if area["id"] == "DE-LU"))
    with pytest.raises(RelayParseError):
        parse_bundled(document)


async def test_a_missing_or_refused_file_is_no_bundled_catalogue(hass: HomeAssistant, tmp_path: Path) -> None:
    assert await async_load_bundled(hass, tmp_path / "absent.json") is None
    broken = tmp_path / "areas.json"
    broken.write_text("{not json", encoding="utf-8")
    assert await async_load_bundled(hass, broken) is None
    loaded = await async_load_bundled(hass)
    assert loaded is not None and "SE4" in loaded.catalogue.area_ids


# ------------------------------------------------------------------ the repository's fallback


async def test_the_bundled_list_answers_until_the_relays_is_held(
    hass: HomeAssistant, transport: StubTransport, clock: Clock, bundled
) -> None:
    repository = PriceRepository(hass, base_url=BASE_URL, session=transport, now=clock, bundled=bundled)

    before = repository.catalogue_snapshot()
    assert (before.state, before.source, before.fetched_at) == ("ready", "bundled", None)
    assert before.catalogue is bundled.catalogue
    # Its calendars too: Portugal's display day is cut from Madrid files.
    assert repository.calendars("PT") == ("Europe/Lisbon", "Europe/Madrid")

    # The relay cannot be reached: the bundled list stays, with the failure beside it.
    transport.serve("/v1/areas.json", 500, "")
    failed = await repository.async_get_catalogue()
    assert (failed.state, failed.source, failed.attempt_error) == ("stale", "bundled", "http_status")
    assert failed.catalogue is bundled.catalogue

    # The relay's list, once held, is the one answered.
    transport.serve_area()
    fetched = await repository.async_get_catalogue()
    assert (fetched.state, fetched.source) == ("ready", "network")
    assert fetched.catalogue is not bundled.catalogue
    assert repository.catalogue_snapshot().catalogue is fetched.catalogue


async def test_without_a_bundled_list_nothing_changes(
    hass: HomeAssistant, transport: StubTransport, clock: Clock
) -> None:
    repository = PriceRepository(hass, base_url=BASE_URL, session=transport, now=clock)
    assert repository.catalogue_snapshot().catalogue is None
    transport.serve("/v1/areas.json", 500, "")
    failed = await repository.async_get_catalogue()
    assert (failed.state, failed.catalogue) == ("unavailable", None)


async def test_the_bundled_list_is_never_stored(
    hass: HomeAssistant, transport: StubTransport, clock: Clock, bundled
) -> None:
    repository = PriceRepository(hass, base_url=BASE_URL, session=transport, now=clock, bundled=bundled)
    assert repository._payload()["catalogue"] is None


# ------------------------------------------------------------------ the sync tool's guard


def test_the_sync_tool_refuses_to_lose_a_route() -> None:
    old = shipped()
    assert lost_routes(old, copy.deepcopy(old)) == []
    new = copy.deepcopy(old)
    next(area for area in new["areas"] if area["id"] == "DE-LU")["routes"].pop("nordpool")
    new["areas"] = [area for area in new["areas"] if area["id"] != "SE3"]
    assert lost_routes(old, new) == ["DE-LU: lost its nordpool route", "SE3: the area is gone"]
    # A gained area or route is no loss.
    assert lost_routes(new, old) == []

// The language files served beside the card: one rule, shared by the build, `check-dist` and the
// generated module the card is compiled with, so the three cannot disagree about a file's name.
//
// English is compiled into the bundle (it is the fallback and needs no request). Every other
// language becomes `<lang>.<hash>.json` in custom_components/spotnav/www/i18n/: compact JSON, named
// by the first 8 hex characters of its own SHA-256, so a changed translation is a new URL and the
// file may be cached hard.

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE_DIR = resolve(here, "../src/i18n");
export const LANGUAGE_DIR = resolve(here, "../../custom_components/spotnav/www/i18n");

/** The languages served as files; English is bundled. Keep in step with `LANGUAGES` in src/i18n. */
export const SERVED_LANGUAGES = ["sv", "nb", "da", "fi", "de", "nl", "fr", "es"];

/** `[{ language, name, bytes }]` for every served language, from the source JSON. */
export function languageFiles() {
  return SERVED_LANGUAGES.map((language) => {
    const words = JSON.parse(readFileSync(resolve(SOURCE_DIR, `${language}.json`), "utf8"));
    const bytes = Buffer.from(`${JSON.stringify(words)}\n`, "utf8");
    const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 8);
    return { language, name: `${language}.${hash}.json`, bytes };
  });
}

/** The generated module the card imports: language -> file name. */
export function languageModule(files = languageFiles()) {
  const names = Object.fromEntries(files.map(({ language, name }) => [language, name]));
  return `// Generated by frontend/scripts/write-languages.mjs from src/i18n/*.json. Do not edit: run
// \`npm run languages:write\`. The files themselves are in custom_components/spotnav/www/i18n/.
export const LANGUAGE_FILES: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};
`;
}
